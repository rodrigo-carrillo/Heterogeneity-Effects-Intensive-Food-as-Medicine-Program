"""Smallest difference in effect that a one-variable subgroup test could detect (post hoc, 2026-11-10).

    python code/subgroup_detectable_difference.py
        ->  outputs/v3/subgroup_detectable_difference.{csv,md}

Reads only aggregate outputs of the main runs (outputs/v3/<outcome>/table_subgroups.csv and
results.json); no patient-level data. For each subgroup variable prespecified by the trial
investigators, the SE of the difference in effect between its 2 levels is recovered from the 95% CIs
of the subgroup effects (CI = est +/- 1.96 SE, as in hte_food_as_medicine.py), and the minimum
detectable difference (MDD) with 80% power for a 2-sided test is

    MDD = (z_{1 - alpha/2} + z_{0.80}) x SE_diff,

at alpha = .05 (one variable tested alone) and alpha = .05/7 (the first step of the Holm adjustment
across the 7 prespecified variables). Values are also given in SDs of the outcome, the scale of the
positive control (calibration and rank-weighted tests: 1 SD detected, 0.5 SD not; METHODS.md section 2).
This uses the observed SEs, not the observed effects (it is not "observed power").
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import norm

ROOT = Path(__file__).resolve().parents[1]
V3 = ROOT / "outputs" / "v3"
OUTCOMES = ["hba1c", "weight", "sbp", "ed_ip"]
N_VARS, POWER, ALPHA = 7, 0.80, 0.05

rows = []
for oc in OUTCOMES:
    sub = pd.read_csv(V3 / oc / "table_subgroups.csv")
    sub = sub[sub.family == "Doyle pre-specified"]
    sd_y = json.loads((V3 / oc / "results.json").read_text(encoding="utf-8"))["sd_y"]
    for name, g in sub.groupby("subgroup", sort=False):
        a, b = g.iloc[0], g.iloc[1]
        se = np.hypot((a.hi - a.est) / 1.96, (b.hi - b.est) / 1.96)
        diff = b.est - a.est
        row = {"outcome": oc, "subgroup": name, "levels": f"{b.level} minus {a.level}",
               "diff": diff, "se_diff": se, "p_interaction": a.p_interaction, "p_holm": a.p_holm,
               "sd_y": sd_y}
        for label, alpha in [("alone", ALPHA), ("holm_step1", ALPHA / N_VARS)]:
            mdd = (norm.ppf(1 - alpha / 2) + norm.ppf(POWER)) * se
            row[f"mdd80_{label}"] = mdd
            row[f"mdd80_{label}_sd"] = mdd / sd_y
        rows.append(row)

tab = pd.DataFrame(rows)
tab.to_csv(V3 / "subgroup_detectable_difference.csv", index=False)

lines = ["# Minimum detectable difference, one-variable subgroup tests (post hoc)", "",
         "80% power, 2-sided; `alone`: alpha = .05; `holm_step1`: alpha = .05/7. "
         "Differences in outcome units and in SDs of the outcome. Generated by "
         "`code/subgroup_detectable_difference.py` from the aggregate outputs.", "",
         "| Outcome | Subgroup variable | Observed difference | SE | MDD alone | MDD Holm step 1 | "
         "MDD alone (SD) | MDD Holm step 1 (SD) | Holm P |",
         "|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    lines.append(f"| {r['outcome']} | {r['subgroup']} ({r['levels']}) | {r['diff']:+.2f} | {r['se_diff']:.2f} | "
                 f"{r['mdd80_alone']:.2f} | {r['mdd80_holm_step1']:.2f} | {r['mdd80_alone_sd']:.2f} | "
                 f"{r['mdd80_holm_step1_sd']:.2f} | {r['p_holm']:.3f} |")
(V3 / "subgroup_detectable_difference.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))
