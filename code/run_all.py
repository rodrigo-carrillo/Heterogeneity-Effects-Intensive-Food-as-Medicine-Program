"""
Run the HTE pipeline (code/hte_food_as_medicine.py) for every outcome x
covariate set, then compile one cross-outcome summary.

  python code/run_all.py               # all runs, full settings (~1.5 h)
  python code/run_all.py --fast        # smoke test of every run (~5 min)
  python code/run_all.py --summary-only   # just rebuild the summary from results.json
  python code/run_all.py --jobs 2      # two runs at a time (each already uses ~5 cores)

Writes outputs/v3/summary_across_outcomes.{md,csv} (outputs/v3_fast/ with --fast).
"""
import argparse
import json
import subprocess
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "code" / "hte_food_as_medicine.py"

# (run id, CLI flags). All runs are complete case (no imputation). "main" = no
# lipids; "ldl_cc" = baseline LDL added to X (patients with LDL measured).
RUNS = [(f"{o}{suffix}", ["--outcome", o, *flags])
        for o in ("hba1c", "weight", "sbp", "ed_ip")
        for suffix, flags in (("", []), ("_ldl_cc", ["--ldl"]))]

parser = argparse.ArgumentParser()
parser.add_argument("--fast", action="store_true")
parser.add_argument("--jobs", type=int, default=1)
parser.add_argument("--summary-only", action="store_true")
args = parser.parse_args()
OUT = ROOT / "outputs" / ("v3_fast" if args.fast else "v3")

if not args.summary_only:
    pending, running = list(RUNS), {}
    while pending or running:
        while pending and len(running) < args.jobs:
            rid, flags = pending.pop(0)
            cmd = [sys.executable, str(SCRIPT), *flags] + (["--fast"] if args.fast else [])
            print(f"[{time.strftime('%H:%M:%S')}] start {rid}", flush=True)
            running[rid] = subprocess.Popen(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
        for rid, p in list(running.items()):
            if p.poll() is None:
                continue
            del running[rid]
            status = "done" if p.returncode == 0 else f"FAILED (exit {p.returncode})"
            print(f"[{time.strftime('%H:%M:%S')}] {status} {rid}", flush=True)
            if p.returncode != 0:
                print(p.stderr.read().decode(errors="replace")[-2000:])
        time.sleep(1)


# ---- Cross-outcome summary ---------------------------------------------------
def ci(x, d=2):
    return f"{x[0]:+.{d}f} ({x[1]:+.{d}f} to {x[2]:+.{d}f})"


rows = []
for rid, _ in RUNS:
    f = OUT / rid / "results.json"
    if not f.exists():
        print(f"missing {f.relative_to(ROOT)}; skipped")
        continue
    r = json.loads(f.read_text())
    a = r["ate_aipw"]
    # Smallest injected positive-control contrast that BOTH omnibus tests detect.
    pc = [s for s in r["sensitivity"] if s["analysis"].startswith("PC")]
    hit = [s["analysis"] for s in pc if s["blp_p_one_sided"] < 0.05 and s["autoc_p_one_sided"] < 0.05]
    top = next(iter(r["split_stability_top"].items()), ("-", np.nan))
    rows.append({
        "run": rid, "outcome": r["config"]["outcome"],
        "covariates": "with LDL" if r["config"]["ldl_in_main"] else "main (no lipids)",
        "n": r["n"], "n_treat": r["n_treat"],
        "paper_adjusted": ci(r["replication"]["paper_adj"]),
        "paper_model_replicated": ci(r["replication"]["paper_model"]),
        "aipw_ate": ci([a["est"], a["lo"], a["hi"]]),
        "blp_beta2": f"{r['blp']['beta2']:+.2f} ({r['blp']['beta2_se']:.2f})",
        "blp_p_one_sided": r["blp"]["p_one_sided"],
        "autoc_p_one_sided": r["rate_autoc"]["p_one_sided"],
        "blp_covariates_joint_p": r["blp_covariates_joint_p"],
        "ancova_interactions_joint_p": r["ancova_interactions_joint_p"],
        "ancova_interactions_randomization_p": r["ancova_interactions_randomization_p"],
        "prespecified_min_p_holm": r["prespecified_min_p_holm"],
        "honest_tree_leaf_p": r["honest_tree_leaf_p"],
        "top_root_split": f"{top[0]} ({top[1]:.0%})",
        "heterogeneity_detected": r["heterogeneity_detected"],
        "smallest_pc_detected": (hit[0].split("contrast ")[1].split(" (")[0] if hit else "not detected up to 1 SD"),
        "sd_y": r["sd_y"],
    })
summ = pd.DataFrame(rows)
if len(summ):
    summ.to_csv(OUT / "summary_across_outcomes.csv", index=False)
    units = {"hba1c": "pp", "weight": "kg", "sbp": "mm Hg", "ed_ip": "pp"}
    show = summ.assign(outcome=summ.outcome + " (" + summ.outcome.map(units) + ")")
    md = f"""# HTE across outcomes (auto-generated by code/run_all.py)

{'FAST smoke-test settings - do not interpret.' if args.fast else 'Full settings.'}
Complete case throughout: every patient has the outcome and every modifier observed; nothing is imputed.
All outcomes at 6 months; negative effect = lower with the program.
"Detected" = BLP calibration AND RATE (AUTOC) one-sided p < 0.05 on out-of-fold CATEs.
Joint linear tests: BLP of AIPW scores on all covariates, and ANCOVA treatment x covariate
interactions (HC1 Wald, then a randomization p under a constant-effect null, which is the
calibrated one; the asymptotic Wald tests can over-reject with ~20 terms).
Smallest PC detected = smallest injected older-vs-younger contrast (0.25 / 0.5 / 1 SD of Y)
that both omnibus tests recover: a rough minimum detectable heterogeneity.

## Average effects
{show[['outcome', 'covariates', 'n', 'n_treat', 'paper_adjusted', 'paper_model_replicated', 'aipw_ate']].to_markdown(index=False)}

Weight: the paper's unadjusted Table 3 difference is in pounds although labelled kg; its adjusted
+1.95 kg rests on 5 imputed baselines (outputs/replication/). Our analysis is in kg (lb / 2.20462).

## Heterogeneity tests
{show[['outcome', 'covariates', 'blp_beta2', 'blp_p_one_sided', 'autoc_p_one_sided', 'blp_covariates_joint_p', 'ancova_interactions_joint_p', 'ancova_interactions_randomization_p', 'prespecified_min_p_holm', 'honest_tree_leaf_p', 'heterogeneity_detected']].round(3).to_markdown(index=False)}

## Data-driven subgroup stability and power
{show[['outcome', 'covariates', 'top_root_split', 'smallest_pc_detected']].to_markdown(index=False)}

Per-run details: outputs/{OUT.name}/<run>/results_summary.md
"""
    (OUT / "summary_across_outcomes.md").write_text(md)
    print(md)
